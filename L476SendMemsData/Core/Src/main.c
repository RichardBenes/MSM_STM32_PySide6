/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  /* USER CODE BEGIN 2 */

  setup_gpio();
  setup_uart();

  const uint32_t buff_size = 128;
  char str_buff[buff_size];
  uint32_t transmit_len;

  uint16_t gyro_x = 0;
  uint16_t gyro_y = 20U;
  uint16_t gyro_z = 110;

  board_led_e led_to_blink;

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

	  HAL_Delay(10U);

	  if (GPIOA->IDR & (1U << 1U)) {
		  led_to_blink = RED;
	  } else {
		  led_to_blink = GREEN;
	  }

	  if (led_to_blink == RED) {
		  GPIOB->BSRR |= GPIO_BSRR_BS2;
	  } else {
		  GPIOE->BSRR |= GPIO_BSRR_BS8;
	  }

	  transmit_len = snprintf(str_buff, buff_size, "GX%uY%uZ%u\n",
	  	  gyro_x, gyro_y, gyro_z);

	  for (uint32_t i = 0; i < transmit_len; i += 1) {
		  while ((USART2->ISR & USART_ISR_TXE) == 0U) {}
		  USART2->TDR = str_buff[i];
	  }


	  HAL_Delay(10U);

	  GPIOB->BSRR |= GPIO_BSRR_BR2;
	  GPIOE->BSRR |= GPIO_BSRR_BR8;

	  if (led_to_blink == GREEN) {
		  gyro_x += 1;
		  gyro_y += 2;
		  gyro_z += 3;

		  if (gyro_x > 255) {
			  gyro_x = 0;
		  }

		  if (gyro_y > 255) {
			  gyro_y = 0;
		  }

		  if (gyro_z > 255) {
			  gyro_z = 0;
		  }

	  } else {
		  gyro_x += 10;
		  gyro_y += 10;
		  gyro_z += 10;

		  if (gyro_x > 120) {
			  gyro_x = 50;
		  }

		  if (gyro_y > 140) {
			  gyro_y = 70U;
		  }

		  if (gyro_z > 160U) {
			  gyro_z = 90U;
		  }
	  }
  }
  /* USER CODE END 3 */
}

